int main(void)
{
    HAL_Init();
    SystemClock_Config();

    MX_GPIO_Init();
    MX_USART2_UART_Init();
    MX_I2C1_Init();
    MX_I2C2_Init();

    print("MPU6050 INIT...\r\n");

    MPU6050_Init(&hi2c1, MPU6050_ADDR1);
    MPU6050_Init(&hi2c2, MPU6050_ADDR2);

    print("MPU6050 READY\r\n");

    uint8_t whoami = 0;
    HAL_I2C_Mem_Read(&hi2c1, MPU6050_ADDR1, 0x75, 1, &whoami, 1, HAL_MAX_DELAY);

    char buf[32];
    sprintf(buf, "WHO_AM_I = 0x%02X\r\n", whoami);
    print(buf);

    uint8_t mpu1[14], mpu2[14];

    while (1)
    {
        float Ax1, Ay1, Az1, Gx1, Gy1, Gz1;
        float Ax2, Ay2, Az2, Gx2, Gy2, Gz2;

        MPU6050_ReadRaw(&hi2c1, MPU6050_ADDR1, mpu1);
        MPU6050_ReadRaw(&hi2c2, MPU6050_ADDR2, mpu2);

        MPU6050_Convert(mpu1, &Ax1, &Ay1, &Az1, &Gx1, &Gy1, &Gz1);
        MPU6050_Convert(mpu2, &Ax2, &Ay2, &Az2, &Gx2, &Gy2, &Gz2);

        char out[150];
        sprintf(out,
                "%.2f %.2f %.2f %.2f %.2f %.2f | %.2f %.2f %.2f %.2f %.2f %.2f\r\n",
                Ax1, Ay1, Az1, Gx1, Gy1, Gz1,
                Ax2, Ay2, Az2, Gx2, Gy2, Gz2);

        print(out);
    }
}


